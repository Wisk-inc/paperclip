#!/usr/bin/env node
// Writes packages/shared/src/time-zone-countries.ts: the country (ISO 3166-1
// alpha-2) of every IANA time zone, from tzdata's zone.tab, plus the old names
// tzdata keeps as links (Asia/Calcutta, US/Eastern, Jamaica…), which some
// phones still report. Automa's language "Auto" uses it to tell the country
// from the phone's time zone without asking any service.
//
//   node scripts/generate-time-zone-countries.mjs [--zoneinfo /usr/share/zoneinfo]
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const argv = process.argv.slice(2);
const zoneinfo = argv.includes("--zoneinfo") ? argv[argv.indexOf("--zoneinfo") + 1] : "/usr/share/zoneinfo";
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(repoRoot, "packages", "shared", "src", "time-zone-countries.ts");

const countries = new Map();
for (const line of readFileSync(path.join(zoneinfo, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [country, , zone] = line.split("\t");
  if (/^[A-Z]{2}$/.test(country ?? "") && zone) countries.set(zone, country);
}
const zi = readFileSync(path.join(zoneinfo, "tzdata.zi"), "utf8");
const version = zi.match(/^# version (\S+)/m)?.[1] ?? "unknown";
for (const line of zi.split("\n")) {
  const link = line.match(/^L (\S+) (\S+)$/);
  if (!link) continue;
  const [, target, alias] = link;
  const country = countries.get(target);
  // A link to a zone that spans no single country (Etc/UTC…) says nothing.
  if (country && !countries.has(alias)) countries.set(alias, country);
}
if (countries.size < 400) throw new Error(`Only ${countries.size} time zones read from ${zoneinfo}; refusing to write.`);

const entries = [...countries].sort(([a], [b]) => a.localeCompare(b));
const body = entries.map(([zone, country]) => `  ${JSON.stringify(zone)}: ${JSON.stringify(country)},`).join("\n");
writeFileSync(out, `// Generated by scripts/generate-time-zone-countries.mjs from tzdata ${version}
// (zone.tab and its links). Do not edit by hand.

/** The country (ISO 3166-1 alpha-2) of each IANA time zone, old names included. */
export const TIME_ZONE_COUNTRIES: Readonly<Record<string, string>> = {
${body}
};
`);
console.log(`wrote ${path.relative(repoRoot, out)}: ${entries.length} time zones (tzdata ${version})`);
