#!/usr/bin/env node
/**
 * update-model-catalog.mjs [--from <catalog.json>] [--out <file.ts>]
 *
 * Refreshes Automa's built-in model catalog,
 * packages/shared/src/model-catalog-snapshot.ts: the list a server uses until
 * it has downloaded the catalog itself (its first start, or a phone that has
 * never been online). Run it before a release: `pnpm models:update`.
 *
 * Between releases nothing needs it: every server downloads the catalog on its
 * own (twice a day at most) and keeps a copy, so new models show up by
 * themselves (server/src/services/model-catalog.ts).
 *
 * --from reads a catalog answer saved earlier instead of downloading one.
 * --out writes somewhere else (tests).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CATALOG_URL = "https://openrouter.ai/api/v1/models";
const DEFAULT_OUT = path.join(repoRoot, "packages", "shared", "src", "model-catalog-snapshot.ts");
const TSX_API = path.join(repoRoot, "cli", "node_modules", "tsx", "dist", "esm", "api", "index.mjs");
/** Fewer than this many models is a broken answer, not a catalog. */
const MIN_MODELS = 50;

function option(argv, name) {
  const at = argv.indexOf(name);
  return at >= 0 ? argv[at + 1] : undefined;
}

async function loadParser() {
  if (!existsSync(TSX_API)) throw new Error(`${path.relative(repoRoot, TSX_API)} is missing: run pnpm install first.`);
  const { tsImport } = await import(pathToFileURL(TSX_API).href);
  const module = await tsImport(pathToFileURL(path.join(repoRoot, "packages", "shared", "src", "model-catalog.ts")).href, import.meta.url);
  return module.parseCatalogModels;
}

/** The snapshot module's source for `models`, downloaded at `fetchedAt`. */
export function renderSnapshot(models, fetchedAt) {
  const lines = models.map((model) => `  ${JSON.stringify(model)},`);
  return [
    "// Generated by scripts/update-model-catalog.mjs (pnpm models:update) from the",
    `// public model catalog, downloaded ${fetchedAt}. Do not edit by hand: run the script.`,
    "// A server uses it until it has downloaded the catalog itself.",
    'import type { CatalogModel } from "./model-catalog.js";',
    "",
    `export const MODEL_CATALOG_SNAPSHOT_FETCHED_AT = ${JSON.stringify(fetchedAt)};`,
    "",
    "export const MODEL_CATALOG_SNAPSHOT: CatalogModel[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

export async function main(argv = process.argv.slice(2), { log = console.log } = {}) {
  const parseCatalogModels = await loadParser();
  const from = option(argv, "--from");
  const out = option(argv, "--out") ?? DEFAULT_OUT;
  let body;
  let fetchedAt;
  if (from) {
    body = JSON.parse(readFileSync(from, "utf8"));
    fetchedAt = option(argv, "--fetched-at") ?? new Date().toISOString();
  } else {
    const response = await fetch(CATALOG_URL, { signal: AbortSignal.timeout(30_000) });
    if (!response.ok) throw new Error(`The model catalog answered ${response.status}.`);
    body = await response.json();
    fetchedAt = new Date().toISOString();
  }
  const models = parseCatalogModels(body);
  if (models.length < MIN_MODELS) {
    throw new Error(`The model catalog listed only ${models.length} models; kept the snapshot as it was.`);
  }
  writeFileSync(out, renderSnapshot(models, fetchedAt));
  const newest = models[0];
  log(`model catalog: ${models.length} models written to ${path.relative(process.cwd(), out) || out}; newest ${newest.id} (${new Date(newest.created * 1000).toISOString().slice(0, 10)})`);
  return models.length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  });
}
